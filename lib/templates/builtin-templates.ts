// Helper: build a minimal valid clip with sensible defaults.
function buildClip(opts: {
  id: string;
  trackId: string;
  kind: 'video' | 'audio' | 'image' | 'text';
  timelineStart: number;
  duration: number;
  slotId?: string;
  text?: string;
}): any {
  // V19.1 §5.1: media slots leave assetId EMPTY — the slot system is the
  // legitimate "user-replaceable media" mechanism. The assetId is
  // populated only when the user assigns a real asset via the
  // /api/templates/[id]/use or /apply flow's slot-assignment step.
  // (Previously this used `placeholder-{slotId}` strings which were
  // misleading — they looked like asset references but pointed at no
  // real asset.)
  const hasSlot = !!opts.slotId;
  return {
    id: opts.id,
    trackId: opts.trackId,
    kind: opts.kind,
    // For media clips with a slot: empty assetId (filled in at apply time).
    // For media clips with no slot: empty assetId (rare; templates should
    //   always use a slot for user-replaceable media).
    // For text clips: undefined (text clips don't reference assets).
    assetId: opts.kind === 'text' ? undefined : (hasSlot ? '' : ''),
    assetName: opts.kind === 'text' ? undefined : (hasSlot ? 'Unassigned slot' : 'Unassigned'),
    sourceStart: 0,
    sourceEnd: opts.duration,
    timelineStart: opts.timelineStart,
    duration: opts.duration,
    speed: 1,
    reverse: false,
    frozen: null,
    transform: { x: 0, y: 0, scale: 1, rotation: 0, opacity: 1, anchorX: 0.5, anchorY: 0.5 },
    crop: { top: 0, right: 0, bottom: 0, left: 0 },
    blendMode: 'normal',
    color: {
      exposure: 0, brightness: 0, contrast: 0, highlights: 0, shadows: 0,
      whites: 0, blacks: 0, saturation: 0, vibrance: 0, temperature: 0, tint: 0, hue: 0,
    },
    audio: { volume: 1, pan: 0, fadeIn: 0, fadeOut: 0, muted: false },
    effects: [],
    filters: [],
    transitions: [],
    keyframes: [],
    masks: [],
    slotId: opts.slotId,
    text: opts.kind === 'text' ? {
      text: opts.text || 'Your text',
      fontFamily: 'Inter',
      fontSize: 48,
      fontWeight: 700,
      italic: false,
      letterSpacing: 0,
      lineHeight: 1.2,
      align: 'center' as const,
      color: '#ffffff',
      animation: 'fade' as const,
    } : undefined,
    enabled: true,
  };
}

function buildTrack(id: string, kind: 'video' | 'audio' | 'text' | 'subtitle', name: string): any {
  return {
    id, kind, name, locked: false, hidden: false, solo: false, muted: false, height: 80,
  };
}

// V19.1 §5.2: helper to compute the public thumbnail URL for a template.
// The actual PNGs are generated by scripts/generate-template-thumbnails.ts
// and shipped under /public/templates/{template-id}.png.
function thumbnailUrlFor(templateId: string): string {
  return `/templates/${templateId}.png`;
}

