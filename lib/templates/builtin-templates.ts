// media carry a `slotId` (the slot's stable identifier). The clip's
// `assetId` is intentionally EMPTY until the user assigns a real
// asset to the slot via the /api/templates/[id]/use or /apply flow.
//
// We previously used fake `placeholder-{slotId}` strings as assetId
// values — that was misleading because it looked like a real asset
// reference but pointed at no actual asset. The slot system is the
// legitimate mechanism for "user-replaceable media" — the assetId
// stays empty until a real asset is assigned.
//
// V19.1 §5.2 — Each template has a real `thumbnailUrl` pointing at a
// PNG generated by `scripts/generate-template-thumbnails.ts`. These
// thumbnails are real representative frames (gradient background +
// title text + clip-slot rectangles) — NOT fake gradient fallbacks.
//
